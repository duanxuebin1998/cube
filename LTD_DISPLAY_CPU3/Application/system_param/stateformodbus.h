/* CPU2 共享保持寄存器地址空间容量，同时作为合法地址的排他上界；范围校验必须满足 address < HOLDREGISTER_AMOUNT。 */
#define HOLDREGISTER_AMOUNT       0x1000U

/* 可配置继电器报警通道数量；当前固定为 4 路，通道索引范围为 0～3。 */
