/**
 * @brief 判断[start, start + count)是否完整位于寄存器数组内。
 *
 * @param start 本次连续访问区间的起始寄存器或位地址。
 * @param count 参与本次处理的数据项数量。
 * @param limit 上限。
 * @return true 表示 count 非 0，且半开区间 [start, start + count) 的排他末端不超过 limit；false 表示 count 为 0，或区间末端越过 limit。
 */
static inline bool LtdModbus_RangeWithin(uint16_t start, uint16_t count, uint16_t limit)
{
    return (count != 0U) && ((uint32_t)start + (uint32_t)count <= (uint32_t)limit);
}

/**
 * @brief 判断一个完整区间是否包含另一个完整区间。
 *
 * @param start 本次连续访问区间的起始寄存器或位地址。
 * @param count 参与本次处理的数据项数量。
 * @param target_start 目标起始位置。
 * @param target_count 待判断子区间连续覆盖的寄存器数量。
 * @return true 表示 target_start 不早于 start，且目标区间末端不晚于源区间末端；false 表示目标区间从源区间之前开始，或目标末端越过源区间。
 */
static inline bool LtdModbus_RangeContains(uint16_t start,
                                           uint16_t count,
                                           uint16_t target_start,
                                           uint16_t target_count)
{
    return ((uint32_t)target_start >= (uint32_t)start) &&
           ((uint32_t)target_start + (uint32_t)target_count <=
            (uint32_t)start + (uint32_t)count);
}

/**
 * @brief 判断单个CPU2保持寄存器地址是否位于可写块。
 *
 * @param address 待分类的 CPU2 共享保持寄存器地址；用于判断写权限或四路锁存报警清除槽。
 * @return true 表示地址位于电源或默认命令、自动恢复、电机、油位或罐高、水位、修正、测量配置、AO、继电器、SI 或瓦锡兰，或正式命令的任一允许写块；false 表示地址不在全部可写白名单中。
 */
static inline bool LtdModbus_HoldingRegisterIsWritable(uint16_t address)
{
    /* 协议36只开放原reserved10/11，邻近历史保留区仍只读。 */
    if ((address >= HOLDREGISTER_DEVICEPARAM_LEVEL_REFERENCE_REFRESH_ENABLE) &&
        (address < HOLDREGISTER_DEVICEPARAM_LEVEL_REFERENCE_REFRESH_INTERVAL_MIN + REG_STRIDE)) {
        return true;
    }
    if (((address >= HOLDREGISTER_DEVICEPARAM_POWER_ON_DEFAULT_COMMAND) &&
         (address < HOLDREGISTER_DEVICEPARAM_PROTOCOL_VERSION)) ||
        ((address >= HOLDREGISTER_DEVICEPARAM_FAULT_AUTO_RECOVERY_RETRY_LIMIT) &&
         (address < HOLDREGISTER_DEVICEPARAM_FAULT_AUTO_RECOVERY_RETRY_LIMIT + REG_STRIDE)) ||
        ((address >= HOLDREG_BASE_MOTOR) &&
         (address < HOLDREGISTER_DEVICEPARAM_FINDZERO_DOWN_DISTANCE + REG_STRIDE)) ||
        ((address >= HOLDREG_BASE_OIL_HEIGHT) &&
         (address < HOLDREGISTER_DEVICEPARAM_BOTTOM_ENCODER_CORRECTION_ENABLE + REG_STRIDE)) ||
        ((address >= HOLDREG_BASE_WATER) &&
         (address < HOLDREGISTER_DEVICEPARAM_WATER_LAG_CAP_THRESHOLD + REG_STRIDE)) ||
        ((address >= HOLDREG_BASE_CORRECTION) &&
         (address < HOLDREGISTER_DEVICEPARAM_TAPE_CALIBRATION_TEMPERATURE + REG_STRIDE)) ||
        ((address >= HOLDREG_BASE_MEAS_CONFIG) &&
         (address < HOLDREGISTER_DEVICEPARAM_MOTOR_COMMAND_DISTANCE + REG_STRIDE)) ||
        ((address >= HOLDREG_BASE_AO) &&
         (address < HOLDREGISTER_AO_SIMULATION_ENABLE + REG_STRIDE)) ||
        ((address >= HOLDREGISTER_DEVICEPARAM_RELAY_ALARM_BASE) &&
         (address < HOLDREGISTER_DEVICEPARAM_RELAY_ALARM_END)) ||
        ((address >= HOLDREG_BASE_SI_WARTSILA) &&
         (address < HOLDREGISTER_DEVICEPARAM_SI_PROFILE_BOTTOM_DETECT_INTERVAL + REG_STRIDE)) ||
        ((address >= HOLDREGISTER_DEVICEPARAM_COMMAND) &&
         (address < HOLDREGISTER_DEVICEPARAM_COMMAND + REG_STRIDE))) {
        return true;
    }
    return false;
}

/**
 * @brief 按地址表与权限校验完整FC10写区间。
 *
 * @param start 本次连续访问区间的起始寄存器或位地址。
 * @param count 参与本次处理的数据项数量。
 * @return true 表示寄存器数量非零、完整区间未越界且每个地址都属于当前可写保持寄存器；false 表示数量为零、地址加法越界、区间超出表尾，或包含只读/保留地址。
 */
static inline bool LtdModbus_HoldingWriteRangeIsValid(uint16_t start, uint16_t count)
{
    uint16_t offset;

    if (((start & 1U) != 0U) || ((count & 1U) != 0U) ||
        !LtdModbus_RangeWithin(start, count, HOLDREGISTER_AMOUNT)) {
        return false;
    }
    for (offset = 0U; offset < count; offset++) {
        if (!LtdModbus_HoldingRegisterIsWritable((uint16_t)(start + offset))) {
            return false;
        }
    }
    return true;
}

/**
 * @brief 判断地址是否属于4路清除锁存报警瞬时写槽。
 *
 * @param address 待分类的 CPU2 共享保持寄存器地址；用于判断写权限或四路锁存报警清除槽。
 * @return true 表示地址属于4路清除锁存报警瞬时写槽；false 表示地址不属于4路清除锁存报警瞬时写槽。
 */
static inline bool LtdModbus_HoldingRegisterIsRelayClearAlarm(uint16_t address)
{
    uint16_t channel;

    for (channel = 0U; channel < HOLDREGISTER_RELAY_ALARM_CHANNEL_COUNT; channel++) {
        uint16_t clear_alarm = HOLDREGISTER_DEVICEPARAM_RELAY_CLEAR_ALARM(channel);
        if ((address >= clear_alarm) && (address < clear_alarm + REG_STRIDE)) {
            return true;
        }
    }
    return false;
}

/**
 * @brief 仅当整个FC10区间完全位于7个带参命令前置参数字段内时放行运行态写入。
 *
 * @param start 本次连续访问区间的起始寄存器或位地址。
 * @param count 参与本次处理的数据项数量。
 * @return true 表示非空 FC10 区间完整落在七个带参命令的前置参数连续区域内；false 表示区间为空、起始地址更早、结束地址越过该区域，或混入其他字段。
 */
static inline bool LtdModbus_HoldingWriteIsCommandArgumentOnly(uint16_t start,
                                                               uint16_t count)
{
    return (count != 0U) &&
           ((uint32_t)start >=
            (uint32_t)HOLDREGISTER_DEVICEPARAM_CALIBRATE_OIL_LEVEL) &&
           ((uint32_t)start + (uint32_t)count <=
            (uint32_t)HOLDREGISTER_DEVICEPARAM_MOTOR_COMMAND_DISTANCE + REG_STRIDE);
}

/**
 * @brief 持久化写入排除命令、AO模拟开关和4路清除锁存报警瞬时写槽。
 *
 * @param start 本次连续访问区间的起始寄存器或位地址。
 * @param count 参与本次处理的数据项数量。
 * @return true 表示写区间命中至少一个需要保存到参数存储的字段；false 表示区间为空/无效，或仅覆盖命令、AO 仿真开关及四路清锁存报警瞬时写槽。
 */
static inline bool LtdModbus_HoldingWriteTouchesPersistent(uint16_t start, uint16_t count)
{
    uint16_t offset;

    for (offset = 0U; offset < count; offset++) {
        uint16_t address = (uint16_t)(start + offset);
        if (LtdModbus_HoldingRegisterIsWritable(address) &&
            !((address >= HOLDREGISTER_DEVICEPARAM_COMMAND) &&
              (address < HOLDREGISTER_DEVICEPARAM_COMMAND + REG_STRIDE)) &&
            !((address >= HOLDREGISTER_AO_SIMULATION_ENABLE) &&
              (address < HOLDREGISTER_AO_SIMULATION_ENABLE + REG_STRIDE)) &&
            !LtdModbus_HoldingRegisterIsRelayClearAlarm(address)) {
            return true;
        }
    }
    return false;
}

