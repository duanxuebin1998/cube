const uint8_t *FontCyrillic_GetGlyph(uint32_t codepoint)
{
    uint32_t index;

    if ((codepoint >= 0x0410U) && (codepoint <= 0x0415U)) {
        index = codepoint - 0x0410U;
    } else if (codepoint == 0x0401U) {
        index = 6U;
    } else if ((codepoint >= 0x0416U) && (codepoint <= 0x042FU)) {
        index = 7U + codepoint - 0x0416U;
    } else if ((codepoint >= 0x0430U) && (codepoint <= 0x0435U)) {
        index = 33U + codepoint - 0x0430U;
    } else if (codepoint == 0x0451U) {
        index = 39U;
    } else if ((codepoint >= 0x0436U) && (codepoint <= 0x044FU)) {
        index = 40U + codepoint - 0x0436U;
    } else {
        return NULL;
    }

    return s_cyrillic_font[index];
}
